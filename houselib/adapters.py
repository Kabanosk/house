CLAUDE_MODELS = {"opus": "opus", "sonnet": "sonnet", "haiku": "haiku", "codex": "haiku", "local": "haiku"}
MARKER = "<!-- generated by house adapt: edit core/ or adapters/ in the house repo, not this file -->"

CODEX_DRIVER = """You are a thin driver around Codex CLI (separate usage pool). Do not do the work yourself.
1. If the brief names a task file, use it as the prompt file. Otherwise write a prompt file
   `$HOUSE_DIR/tmp/{id}-<timestamp>.md` with the "Instructions for Codex" below plus your brief.
2. Run `$HOUSE_ROOT/bin/codex-task <prompt-file> <workdir>` in the foreground with the Bash tool's `timeout`
   set to 600000 (10 min; the 2 min default kills Codex mid-run). Codex may edit the workdir and `$HOUSE_DIR`.
   Use `--read-only` only for pure analysis that must write nothing. Tasks for Codex must fit in 10 minutes;
   if one times out, say so and suggest splitting it.
3. Exit code 3 = codex not installed; 2 = bad arguments. Report it; the coordinator falls back to another agent.
4. Afterwards, in the workdir: review `git status` and run `$HOUSE_ROOT/bin/house guard diff <contest> T###
   --worktree <workdir>`; for every VIOLATION restore the file (`git -C <workdir> checkout -- <file>`, or delete
   a new secret file) and report it. Then commit Codex's changes on the task branch yourself
   (`git -C <workdir> add -A`, then `git -C <workdir> commit -m "<task id>: <title>"`); Codex does not commit.
5. Run `$HOUSE_ROOT/bin/house check <contest> T### --worktree <workdir>` (contest name = the AGENTS.md title)
   and read the output. Make sure the expected outputs exist (report in `$HOUSE_DIR/reports/`, rows in
   `$HOUSE_DIR/ideas.md`, ...); if Codex left them out, write them from its output. GREEN → set `status: review`
   (never `done`; the coordinator's `house merge` does the rest); RED → say which criteria failed.
   Return a short summary + paths.

--- Instructions for Codex ---
"""

CLAUDE_MD = f"""@AGENTS.md

{MARKER}

## Claude Code specifics
- The house playbooks replace superpowers' brainstorming, writing-plans and subagent-driven-development here:
  ideas live in `.house/ideas.md`, plans are `.house/tasks/`, execution follows `/house-run`. Do not create
  `docs/superpowers/` plans in a contest repo.
- Task worktrees: `git worktree add .worktrees/T###-slug -b task/T###-slug` from the main checkout. This is
  pre-approved; do not ask for consent. Never use EnterWorktree for the coordinator: the main session stays in the
  main checkout and dispatches subagents into the worktrees.
- Still use superpowers' test-driven-development (coders), dispatching-parallel-agents (independent tasks) and
  verification-before-completion (before claiming anything is done).
"""


def load_profiles(root: Path = HOUSE_ROOT) -> dict[str, tuple[dict, str]]:
    out = {}
    for f in sorted((root / "core/agents").glob("*.md")):
        meta, body = parse_frontmatter(f.read_text())
        out[meta["id"]] = (meta, body)
    return out


def resolve_tier(profile: tuple[dict, str], tools: dict, profiles: dict) -> str | None:
    meta = profile[0]
    tier = meta["model_tier"]
    available = {"codex": tools.get("codex"), "local": bool(tools.get("ollama", {}).get("models"))}
    if tier not in available or available[tier]:
        return tier
    fb = meta.get("fallback")
    if fb is None:
        return None
    return resolve_tier(profiles[fb], tools, profiles) if fb in profiles else fb


def omitted_for(meta: dict, tier: str | None, profiles: dict) -> str | None:
    """Profile id that replaces an omitted agent (e.g. coder-codex without codex → coder), else None."""
    if meta["model_tier"] == "codex" and meta.get("fallback") in profiles and tier != "codex":
        return meta["fallback"]
    return None


def short(desc: str, limit: int = 110) -> str:
    """Roster blurb: the description cut on a word boundary (AGENTS.md is always in context; keep it lean)."""
    desc = " ".join(str(desc).split())
    if len(desc) <= limit:
        return desc
    return desc[:limit].rsplit(" ", 1)[0].rstrip(" ,;-") + "…"


def _read_tools(contest: Path) -> dict:
    return json.loads((contest / ".house/tools.json").read_text())


def _paths(contest: Path, root: Path) -> dict[str, str]:
    return {"$HOUSE_DIR": str((contest / ".house").resolve()), "$HOUSE_ROOT": str(root.resolve())}


def _substitute(text: str, paths: dict[str, str]) -> str:
    for var, value in paths.items():
        text = text.replace(var, value)
    return text




def claude_code(contest: Path, root: Path = HOUSE_ROOT) -> dict[str, str]:
    """Claude Code files for a contest: relpath -> text. Vendor skills are not copied: agents read them from
    $HOUSE_ROOT/vendor/skills by path (copies would only add their descriptions to every session)."""
    tools, profiles, paths = _read_tools(contest), load_profiles(root), _paths(contest, root)
    out = {}
    for pid, (meta, body) in profiles.items():
        if pid == "coordinator":
            continue  # the main session is the coordinator (AGENTS.md)
        tier = resolve_tier((meta, body), tools, profiles)
        if tier is None or omitted_for(meta, tier, profiles):
            continue
        if tier == "codex":
            body = CODEX_DRIVER.format(id=pid) + body
        desc = json.dumps(str(meta["description"]).replace("\n", " "), ensure_ascii=False)
        out[f".claude/agents/{pid}.md"] = _substitute(
            f"---\nname: {pid}\ndescription: {desc}\nmodel: {CLAUDE_MODELS[tier]}\n---\n{body}", paths)
    for skill in sorted((root / "adapters/claude-code/skills").iterdir()):
        out[f".claude/skills/{skill.name}/SKILL.md"] = _substitute((skill / "SKILL.md").read_text(), paths)
    out["CLAUDE.md"] = CLAUDE_MD
    return out


def codex(contest: Path, root: Path = HOUSE_ROOT) -> dict[str, str]:
    tools, profiles = _read_tools(contest), load_profiles(root)
    rows = ["| Agent | Model on this machine | Use for |", "|---|---|---|"]
    for pid, (meta, body) in profiles.items():
        tier = resolve_tier((meta, body), tools, profiles)
        replacement = omitted_for(meta, tier, profiles)
        shown = f"unavailable (use {replacement})" if replacement else (tier or "unavailable")
        rows.append(f"| `{pid}` | {shown} | {short(meta['description'])} |")
    text = (root / "adapters/codex/AGENTS.md.tmpl").read_text()
    for key, value in {
        "{contest_name}": contest.name,
        "{house_dir}": str((contest / ".house").resolve()),
        "{house_root}": str(root.resolve()),
        "{roster}": "\n".join(rows),
        "{coordinator}": profiles["coordinator"][1].strip(),
    }.items():
        text = text.replace(key, value)
    return {"AGENTS.md": MARKER + "\n" + _substitute(text, _paths(contest, root))}


def remove_legacy_vendor_copies(contest: Path, root: Path) -> tuple[list[str], list[str]]:
    """Older adapts copied vendor/skills into .claude/skills. Remove copies identical to the vendor version;
    keep (and report) copies someone edited."""
    removed, kept = [], []
    vendor = root / "vendor/skills"
    for src in sorted(vendor.iterdir()) if vendor.is_dir() else []:
        dst = contest / ".claude/skills" / src.name
        if not dst.is_dir():
            continue
        if _same_tree(src, dst):
            shutil.rmtree(dst)
            removed.append(f".claude/skills/{src.name}")
        else:
            kept.append(f".claude/skills/{src.name}")
    return removed, kept


def _has_marker(path: Path) -> bool:
    return path.is_file() and not path.is_symlink() and MARKER in path.read_text(errors="replace")


def _legacy_owned(contest: Path, root: Path) -> Callable[[str], bool]:
    """Ownership for contests without a manifest. Only if an older adapt demonstrably ran here (our marker in
    AGENTS.md or CLAUDE.md) are our profile and skill names under .claude/ ours; otherwise everything is foreign
    (a freshly adopted team repo may have its own `researcher.md`)."""
    adapted_before = _has_marker(contest / "AGENTS.md") or _has_marker(contest / "CLAUDE.md")
    agents = {f".claude/agents/{pid}.md" for pid in load_profiles(root)}
    skills = {f".claude/skills/{d.name}/SKILL.md" for d in (root / "adapters/claude-code/skills").iterdir()}

    def owned(rel: str) -> bool:
        if rel in ("AGENTS.md", "CLAUDE.md"):
            return _has_marker(contest / rel)
        return adapted_before and (rel in agents or rel in skills)
    return owned


def _commit_owned(contest: Path, paths: list[str]) -> None:
    """Commit exactly the paths adapt owns (written, removed, backups, house files), skipping gitignored ones and
    never the user's other work."""
    candidates = [p for p in dict.fromkeys(paths)
                  if (contest / p).exists() or git(contest, "ls-files", "--", p).strip()]
    if not candidates:
        return
    # check-ignore exits 1 when nothing is ignored, so call it directly instead of via git()
    r = subprocess.run(["git", "check-ignore", *candidates], cwd=contest,
                       capture_output=True, text=True)
    ignored = {line.rstrip("/") for line in r.stdout.split()}
    todo = [p for p in candidates if p not in ignored]
    if not todo:
        return
    git(contest, "add", "-A", "--", *todo)
    if git(contest, "diff", "--cached", "--name-only", "--", *todo).strip():
        git(contest, "commit", "-q", "-m", "chore(house): adapt", "--", *todo)


ALLOW_COMMANDS = ["git status:*", "git diff:*", "git log:*", "git show:*", "git add:*", "git commit:*",
                  "git worktree:*", "git -C:*", "git branch:*", "python3 -m unittest:*", "pytest:*", "uv run:*",
                  "npm test:*", "npm run:*", "npx tsc:*", "ruff check:*"]


def claude_settings(root: Path = HOUSE_ROOT) -> dict:
    """House's part of .claude/settings.local.json: guard hooks + an allowlist for headless sessions."""
    hook = f"{root.resolve()}/bin/house-hook"
    return {
        "hooks": {
            "PreToolUse": [{"matcher": "Edit|Write|MultiEdit|NotebookEdit|Bash",
                            "hooks": [{"type": "command", "command": f"{hook} pre-tool"}]}],
            "SessionStart": [{"hooks": [{"type": "command", "command": f"{hook} session-start"}]}],
        },
        "permissions": {"allow": [f"Bash({root.resolve()}/bin/house:*)", f"Bash({root.resolve()}/bin/codex-task:*)",
                                  *(f"Bash({c})" for c in ALLOW_COMMANDS)]},
    }


def _is_house_hook(hook) -> bool:
    return isinstance(hook, dict) and "house-hook" in str(hook.get("command", ""))


def merge_settings(existing: dict, ours: dict) -> dict:
    """Keep every user key, permission and hook; replace house's own hook commands; no duplicate allow rules."""
    out = dict(existing)
    hooks: dict = {}
    for event, entries in (existing.get("hooks") or {}).items():
        if not isinstance(entries, list):
            continue
        kept = []
        for e in entries:
            if not isinstance(e, dict):
                continue
            mine = [h for h in e.get("hooks", []) if not _is_house_hook(h)]
            if mine:
                kept.append({**e, "hooks": mine})
        hooks[event] = kept
    for event, entries in ours["hooks"].items():
        hooks[event] = [*hooks.get(event, []), *entries]
    out["hooks"] = hooks
    perms = existing.get("permissions")
    perms = dict(perms) if isinstance(perms, dict) else {}
    allow = perms.get("allow") if isinstance(perms.get("allow"), list) else []
    perms["allow"] = list(dict.fromkeys([*allow, *ours["permissions"]["allow"]]))
    out["permissions"] = perms
    return out


def write_local_settings(contest: Path, root: Path = HOUSE_ROOT) -> Path:
    """Hooks live only in .claude/settings.local.json (never committed; listed in .git/info/exclude): the hook
    path is this machine's, and teammates' Claude Code must not run our rules."""
    path = contest / ".claude/settings.local.json"
    try:
        existing = json.loads(path.read_text()) if path.exists() else {}
    except ValueError:
        backup = _backup_name(path)
        path.rename(backup)
        existing = {}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(merge_settings(existing, claude_settings(root)), indent=2) + "\n")
    r = subprocess.run(["git", "rev-parse", "--git-path", "info/exclude"], cwd=contest, capture_output=True,
                       text=True, check=False)
    if r.returncode == 0:
        exclude = (contest / r.stdout.strip()).resolve()
        exclude.parent.mkdir(parents=True, exist_ok=True)
        lines = exclude.read_text().splitlines() if exclude.exists() else []
        if ".claude/settings.local.json" not in lines:
            exclude.write_text("\n".join([*lines, ".claude/settings.local.json"]) + "\n")
    return path


def _backup_name(path: Path) -> Path:
    n, backup = 0, path.with_name(path.name + ".orig")
    while backup.exists():
        n += 1
        backup = path.with_name(f"{path.name}.orig-{n}")
    return backup


@dataclass
class AdaptResult:
    written: list[Path] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def adapt(contest: Path, root: Path = HOUSE_ROOT, detect=doctor.detect) -> AdaptResult:
    install_core(contest, root)  # refresh playbooks/protocols from core; never touches other .house files
    doctor.write(contest, detect())
    generated = {**codex(contest, root), **claude_code(contest, root)}
    corrupt = manifest.is_corrupt(contest)
    old = manifest.load(contest)
    vendor_removed, vendor_kept = remove_legacy_vendor_copies(contest, root)
    res = manifest.apply(contest, generated, old, _legacy_owned(contest, root))
    manifest.save(contest, {rel: manifest.sha256_text(text) for rel, text in generated.items()})
    warnings = [f"{manifest.MANIFEST} was unreadable (merge conflict?); rebuilt it"] if corrupt else []
    warnings += [f"kept the previous {rel} as {b}" for rel, b in zip(res.backed_up, res.backups, strict=True)]
    warnings += [f"{rel} is no longer generated but was edited by hand; left in place" for rel in res.kept_modified]
    warnings += [f"{rel} differs from vendor/skills (local edit?); left in place, agents read the vendor copy"
                 for rel in vendor_kept]
    owned = [*res.written, *res.removed, *vendor_removed, *res.backups,
             manifest.MANIFEST, ".house/tools.json", ".house/playbooks", ".house/protocols"]
    _commit_owned(contest, owned)
    write_local_settings(contest, root)
    return AdaptResult([contest / rel for rel in res.written], warnings)
